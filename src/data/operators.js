export function getRandomOperator(side = 'all') {
  let pool = OPERATORS;
  if (side === 'attacker' || side === 'defense' || side === 'defender') {
    const target = side === 'defense' ? 'defender' : side;
    pool = OPERATORS.filter(op => op.side === target);
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

export function generateRouletteRoll(side = 'all', tier = 'all') {
  let challengePool = CHALLENGES;
  if (tier !== 'all') {
    challengePool = CHALLENGES.filter(c => c.tier === tier);
    if (challengePool.length === 0) challengePool = CHALLENGES;
  }
  if (side !== 'all') {
    challengePool = challengePool.filter(c => c.side === 'all' || c.side === side);
    if (challengePool.length === 0) challengePool = CHALLENGES;
  }

  const challenge = challengePool[Math.floor(Math.random() * challengePool.length)];
  const attachment = CURSED_ATTACHMENTS[Math.floor(Math.random() * CURSED_ATTACHMENTS.length)];

  return {
    challenge,
    attachment
  };
}
